#!/usr/bin/env python3
"""Generate the curated ROM API from an RGBDS symbol file (no ROM required)."""

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def generate(sym, allow):
    symbols = {}
    for line in sym.splitlines():
        fields = line.split()
        if len(fields) == 2 and ":" in fields[0]:
            bank, address = fields[0].split(":")
            symbols[fields[1]] = (int(bank, 16), int(address, 16))
    labels = [
        line.strip()
        for line in allow.splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    ]
    if len(labels) != len(set(labels)):
        raise ValueError("Duplicate allow-list label")
    lines = [
        "package linksawakening.rom;",
        "/** Generated by tools/rom/gen_symbols.py; do not edit. See docs/ROM_SYMBOLS.md. */",
        "public final class RomSymbols { private RomSymbols() {}",
    ]
    for label in labels:
        bank, address = symbols[label]
        lines.append(
            f"    public static final RomAddress {label} = new RomAddress(0x{bank:02X}, 0x{address:04X});"
        )
    return "\n".join(lines + ["}", ""])


def check_without_sym(source, allow):
    """Validate curated labels/order/format; cannot independently verify addresses."""
    entries = re.findall(
        r"RomAddress (\w+) = new RomAddress\(0x([0-9A-F]+), 0x([0-9A-F]+)\)", source
    )
    sym = "\n".join(f"{bank}:{address} {label}" for label, bank, address in entries)
    return source == generate(sym, allow)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("sym", type=Path, nargs="?")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = ROOT / "java/src/main/java/linksawakening/rom/RomSymbols.java"
    allow = (ROOT / "tools/rom/symbols.txt").read_text()
    if args.sym is None:
        if not args.check:
            parser.error("A .sym file is required to generate symbols")
        try:
            valid = check_without_sym(output.read_text(), allow)
        except (KeyError, ValueError):
            valid = False
        if not valid:
            parser.error("Generated labels, ordering or format are stale")
        parser.exit(message="Symbols structurally consistent; addresses require a .sym check.\n")
    result = generate(args.sym.read_text(), allow)
    if args.check:
        if output.read_text() != result:
            parser.error("Generated symbols are stale")
    else:
        output.write_text(result)
